"""Run the simulator for every parameter file in params/ and export the results
for the microsite as site/data/results.js.

    python scripts/export_site_data.py            # all params/*.json
    python scripts/export_site_data.py --runs 3000 params/bahrain_2024.json

The output is a .js file (not .json) so site/index.html also works when you
open it straight from disk by double-clicking - browsers block fetch() on file://.
"""
from __future__ import annotations

import argparse
import json
import sys
from dataclasses import asdict
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

import numpy as np  # noqa: E402

from strategy_sim.model import lap_trace, race_time  # noqa: E402
from strategy_sim.montecarlo import (best_per_family, draw_scenarios, sc_summary,  # noqa: E402
                                     screen_strategies, simulate_many)
from strategy_sim.params import RaceParams  # noqa: E402
from strategy_sim.strategies import Strategy, enumerate_strategies  # noqa: E402
from strategy_sim.undercut import undercut_grid  # noqa: E402

ROW_COLS = ["strategy", "stops", "compounds", "gap_to_best_s", "risk_sd_s",
            "p_fastest", "p_beats_best", "deterministic_s", "mean_s"]


def _rows(df, n):
    out = []
    for _, r in df.head(n).iterrows():
        d = {c: (r[c].item() if hasattr(r[c], "item") else r[c]) for c in ROW_COLS}
        d["pit_laps"] = [int(x) for x in r["pit_laps"]]
        out.append(d)
    return out


def race_payload(path: Path, runs: int, seed: int) -> dict:
    p = RaceParams.from_json(path)
    all_s = enumerate_strategies(p.total_laps, tuple(p.compounds), 2, p.min_stint)
    cands = screen_strategies(all_s, p, keep=40)
    df, _ = simulate_many(cands, p, runs, seed)
    fam = best_per_family(df)

    # 1-stop pit window curves (deterministic)
    comps = [c for c in ("SOFT", "MEDIUM", "HARD") if c in p.compounds]
    laps = list(range(p.min_stint, p.total_laps - p.min_stint + 1))
    curves = {}
    for a in comps:
        for b in comps:
            if a != b:
                curves[f"{a[0]}-{b[0]}"] = [round(race_time(Strategy((a, b), (l,)), p), 3) for l in laps]

    # Undercut grid (medium -> hard if available)
    old = "MEDIUM" if "MEDIUM" in p.compounds else comps[0]
    new = "HARD" if "HARD" in p.compounds else comps[-1]
    ug = undercut_grid(p, tyre_age=min(20, p.total_laps // 3), old_compound=old, new_compound=new, n_runs=3000)
    piv = ug.pivot(index="gap_s", columns="laps_b_stays_out", values="p_success")

    best = df.iloc[0]
    best_s = Strategy(tuple(best["compounds"].split("-")), tuple(int(x) for x in best["pit_laps"]))
    trace = lap_trace(best_s, p)
    bounds = (0, *best_s.pit_laps, p.total_laps)
    stints = [{"compound": c, "from": a + 1, "to": b} for c, a, b in zip(best_s.compounds, bounds, bounds[1:])]

    params = asdict(p)
    params["compounds"] = {k: asdict(v) for k, v in p.compounds.items()}
    return {
        "id": path.stem,
        "circuit": p.circuit,
        "params": params,
        "runs": runs,
        "nStrategies": len(all_s),
        "nSimulated": len(cands),
        "top": _rows(df, 20),
        "families": _rows(fam, 12),
        "pitWindow": {"laps": laps, "curves": curves},
        "undercut": {"old": old, "new": new, "tyreAge": min(20, p.total_laps // 3),
                     "gaps": [float(g) for g in piv.index], "ks": [int(k) for k in piv.columns],
                     "p": np.round(piv.values, 3).tolist()},
        "scenario": sc_summary(draw_scenarios(p, runs, seed)),
        "bestTrace": {"times": np.round(trace, 3).tolist(), "stints": stints, "label": best_s.label},
    }


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("files", nargs="*", help="params JSON files (default: params/*.json)")
    ap.add_argument("--runs", type=int, default=4000)
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--out", default=str(ROOT / "site" / "data" / "results.js"))
    a = ap.parse_args(argv)

    files = [Path(f) for f in a.files] or sorted((ROOT / "params").glob("*.json"))
    # Put real fitted races first, the illustrative example last
    files.sort(key=lambda f: (f.stem.startswith("example"), f.stem))
    races = []
    for f in files:
        print(f"simulating {f.name} ...")
        races.append(race_payload(f, a.runs, a.seed))

    data = {"generated": datetime.now(timezone.utc).isoformat(timespec="seconds"), "races": races}
    out = Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("// Generated by scripts/export_site_data.py - do not edit by hand\n"
                   "window.STRATEGY_DATA = " + json.dumps(data, separators=(",", ":")) + ";\n")
    print(f"wrote {out} ({out.stat().st_size / 1024:.0f} KB, {len(races)} race(s))")


if __name__ == "__main__":
    main()
